    func testConfigDescriptor5() throws {
        let getDescriptorConfigData = Data([
            0x09, 0x02, 0x2c, 0x00, 0x01, 0x01, 0x00, 0xa0,
            0x70, 0x09, 0x04, 0x00, 0x00, 0x02, 0x08, 0x06,
